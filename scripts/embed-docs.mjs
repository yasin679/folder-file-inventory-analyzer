// Embeds the seven guides (Markdown + screenshots + PDFs) into the app so a single
// shared link or file carries the complete application with its documentation.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

// Same order and PDF names as docs/build/build_pdfs.py.
const docs = [
  ['user-guide', 'IA-UG-01_User_Guide'],
  ['installation-and-administration', 'IA-IG-02_Installation_and_Administration_Guide'],
  ['quick-start', 'IA-QS-03_Quick_Start'],
  ['faq-and-troubleshooting', 'IA-FAQ-04_FAQ_and_Troubleshooting'],
  ['technical-design', 'IA-TD-05_Technical_Design'],
  ['uat-test-cases', 'IA-UAT-06_UAT_Test_Cases'],
  ['release-notes', 'IA-RN-07_Release_Notes_v1.2'],
];

function frontMatter(text) {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  const meta = {};
  if (!m) return { meta, body: text };
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':');
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return { meta, body: text.slice(m[0].length) };
}

const images = {};
const out = docs.map(([slug, pdfName]) => {
  const { meta, body } = frontMatter(readFileSync(`docs/${slug}.md`, 'utf8'));
  for (const [, name] of body.matchAll(/\]\(images\/([^)]+)\)/g)) {
    images[name] ??= `data:image/jpeg;base64,${readFileSync(`docs/images/${name}`).toString('base64')}`;
  }
  return {
    id: meta.id, slug, title: meta.title, subtitle: meta.subtitle ?? '', audience: meta.audience ?? '',
    pdfName: `${pdfName}.pdf`,
    markdown: body.replace(/^\s*# .*\n/, ''), // the title is shown in the guide's header
    pdf: readFileSync(`docs/pdf/${pdfName}.pdf`).toString('base64'),
  };
});

mkdirSync('src/generated', { recursive: true });
writeFileSync('src/generated/docs.ts', `// Generated by scripts/embed-docs.mjs — do not edit. Run \`npm run docs:embed\` after changing docs/.
export interface EmbeddedDoc { id: string; slug: string; title: string; subtitle: string; audience: string; pdfName: string; markdown: string; pdf: string }
export const DOCS: EmbeddedDoc[] = ${JSON.stringify(out)};
export const DOC_IMAGES: Record<string, string> = ${JSON.stringify(images)};
`);
console.log(`embedded ${out.length} documents, ${Object.keys(images).length} screenshots`);
