// Embeds the user documents (Markdown text + PDF/Word files) into the app so a single
// shared link or file carries the complete application with its guides.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const docs = [
  { id: 'user', title: 'User Guide', md: 'User Guide.md', file: 'Inventory Analyzer - User Guide' },
  { id: 'setup', title: 'Setup & Administration Guide', md: 'Setup and Administration Guide.md', file: 'Inventory Analyzer - Setup and Administration Guide' },
  { id: 'release', title: 'Release Notes', md: 'Release Notes.md', file: 'Inventory Analyzer - Release Notes' },
];
const out = docs.map((d) => ({
  id: d.id, title: d.title, fileBase: d.file,
  markdown: readFileSync(`docs/${d.md}`, 'utf8'),
  pdf: readFileSync(`docs/${d.file}.pdf`).toString('base64'),
  docx: readFileSync(`docs/${d.file}.docx`).toString('base64'),
}));
mkdirSync('src/generated', { recursive: true });
writeFileSync('src/generated/docs.ts', `// Generated by scripts/embed-docs.mjs — do not edit. Run \`npm run docs:embed\` after changing docs/.
export interface EmbeddedDoc { id: string; title: string; fileBase: string; markdown: string; pdf: string; docx: string }
export const DOCS: EmbeddedDoc[] = ${JSON.stringify(out)};
`);
console.log(`embedded ${out.length} documents`);
